#!/usr/bin/env python3
"""Opt-in real embedded-WASM browser smoke for Reverse Clip.

Requirements: Python playwright, a Chromium executable or Playwright Chromium,
native ffmpeg + ffprobe, and both dist HTML files generated by build-standalone.
No media fixtures, web requests, or credentials are needed to RUN this test.
This uses about:blank/page.set_content, NOT a direct file:// verification.
"""
import json
import os
from pathlib import Path
import subprocess
import tempfile

from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[2]
DIST=ROOT/"dist"

def run(*args):
    return subprocess.check_output(args,stderr=subprocess.PIPE)

def make_source(root):
    frames=root/"frames"
    frames.mkdir()
    for i in range(50):
        data=bytes([20+4*i,5,5])*160*90
        (frames/f"{i:03d}.ppm").write_bytes(b"P6\n160 90\n255\n"+data)
    output=root/"source.mp4"
    subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-y",
        "-framerate","10","-i",str(frames/"%03d.ppm"),"-c:v","libx264",
        "-crf","0","-preset","ultrafast","-pix_fmt","yuv420p",str(output)],
        check=True)
    return output

def check_file(output):
    result=json.loads(run("ffprobe","-v","error","-show_entries",
        "stream=codec_name,width,height,nb_frames:format=duration","-of","json",str(output)))
    assert result["streams"][0]["codec_name"]=="h264",result
    assert int(result["streams"][0]["nb_frames"])==75,result
    assert abs(float(result["format"]["duration"])-5)<0.06,result
    raw=run("ffmpeg","-hide_banner","-loglevel","error","-i",str(output),
        "-vf","scale=1:1:flags=neighbor,format=rgb24",
        "-fps_mode","passthrough","-f","rawvideo","-pix_fmt","rgb24","pipe:1")
    values=list(raw[::3])
    assert len(values)==75, f"unexpected frame count {len(values)}"
    assert all(a>=b-3 for a,b in zip(values,values[1:])),values

def main():
    with tempfile.TemporaryDirectory(prefix="reverse-clip-smoke-") as tmp:
        folder=Path(tmp)
        source=make_source(folder)
        with sync_playwright() as pw:
            kwargs={"headless":True,"args":["--no-sandbox","--disable-dev-shm-usage"]}
            if os.environ.get("CHROMIUM_EXE"):
                kwargs["executable_path"]=os.environ["CHROMIUM_EXE"]
            browser=pw.chromium.launch(**kwargs)
            try:
                for variant in ("index.html","index.self-extract.html"):
                    page=browser.new_page(viewport={"width":390,"height":800},accept_downloads=True)
                    errors=[]
                    requests=[]
                    page.on("pageerror",lambda e:errors.append(str(e)))
                    page.on("console",lambda m:errors.append(m.text) if m.type=="error" else None)
                    page.on("request",lambda r:requests.append(r.url))
                    page.set_content((DIST/variant).read_text(encoding="utf-8"),
                        wait_until="domcontentloaded",timeout=45000)
                    page.locator("#sourceInput").wait_for(timeout=15000)
                    page.locator("#sourceInput").set_input_files(str(source))
                    page.locator("#reversePanel").wait_for(state="visible",timeout=15000)
                    page.locator("#rangeEnd").fill("5")
                    page.locator("#rangeEnd").dispatch_event("change")
                    page.locator("#qualityInput").select_option("360")
                    assert page.locator("#reverseButton").is_enabled()
                    page.locator("#reverseButton").click()
                    # A conversion failure must be surfaced rather than waiting forever.
                    page.wait_for_function("""() =>
                      !document.querySelector('#resultArea').hidden ||
                      !document.querySelector('#reverseErrorDetails').hidden""",
                      timeout=120000)
                    if page.locator("#reverseErrorDetails").is_visible():
                        raise AssertionError(page.locator("#reverseErrorDetail").inner_text())
                    with page.expect_download(timeout=15000) as download:
                        page.locator("#saveReverseButton").click()
                    out=folder/(variant+".mp4")
                    download.value.save_as(out)
                    check_file(out)
                    assert not page.evaluate("document.documentElement.scrollWidth>innerWidth")
                    assert not errors,errors
                    assert not [url for url in requests if url.startswith(("http://","https://"))],requests
                    print("PASS",variant,"5s / 75 frames / descending markers / local save / no external requests")
                    page.close()
            finally:
                browser.close()

if __name__=="__main__":
    main()
